SET SCHEMA SREERAMC1;

-- Generic pattern shown for PPQ_HEADER; replicate for every PPQ_* table
-- by copying this trigger and changing the table/column list.
CREATE OR REPLACE TRIGGER TRG_PPQ_HEADER_AUD
  AFTER INSERT OR UPDATE OR DELETE ON PPQ_HEADER
  REFERENCING NEW ROW AS N OLD ROW AS O
  FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
  DECLARE V_ACTION CHAR(1);
  DECLARE V_USER   VARCHAR(10);
  DECLARE V_PID    BIGINT;

  SET V_USER = COALESCE(SESSION_USER, 'SYSTEM');

  IF INSERTING THEN
    SET V_ACTION = 'I'; SET V_PID = N.PROTOCOL_ID;
    INSERT INTO PPQ_AUDIT (AUDIT_ID, PROTOCOL_ID, TABLE_NAME, ACTION, KEY_VALUE, COLUMN_NAME, OLD_VA
      VALUES (NEXT VALUE FOR SEQ_AUDIT_ID, V_PID, 'PPQ_HEADER', V_ACTION, CHAR(N.PROTOCOL_ID), 'STAT
  ELSEIF UPDATING THEN
    SET V_ACTION = 'U'; SET V_PID = N.PROTOCOL_ID;
    IF N.STATUS <> O.STATUS THEN
      INSERT INTO PPQ_AUDIT (AUDIT_ID, PROTOCOL_ID, TABLE_NAME, ACTION, KEY_VALUE, COLUMN_NAME, OLD_
        VALUES (NEXT VALUE FOR SEQ_AUDIT_ID, V_PID, 'PPQ_HEADER', V_ACTION, CHAR(N.PROTOCOL_ID), 'ST
    END IF;
  ELSEIF DELETING THEN
    SET V_ACTION = 'D'; SET V_PID = O.PROTOCOL_ID;
    INSERT INTO PPQ_AUDIT (AUDIT_ID, PROTOCOL_ID, TABLE_NAME, ACTION, KEY_VALUE, COLUMN_NAME, OLD_VA
      VALUES (NEXT VALUE FOR SEQ_AUDIT_ID, V_PID, 'PPQ_HEADER', V_ACTION, CHAR(O.PROTOCOL_ID), 'STAT
  END IF;
END;

-- Workflow guard: block Approved unless every PPQ_APPROVAL row for the
-- protocol is APPROVED, and block Approved if any linked equipment
-- qualification is incomplete.
CREATE OR REPLACE TRIGGER TRG_PPQ_HEADER_WORKFLOW
  BEFORE UPDATE OF STATUS ON PPQ_HEADER
  REFERENCING NEW ROW AS N OLD ROW AS O
  FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
  DECLARE V_OPEN_APPR INTEGER;
  DECLARE V_EQP_INCOMPLETE INTEGER;

  IF N.STATUS = 'APPROVED' THEN
    SET V_OPEN_APPR = (SELECT COUNT(*) FROM PPQ_APPROVAL A WHERE A.PROTOCOL_ID = O.PROTOCOL_ID AND A
    SET V_EQP_INCOMPLETE = (SELECT COUNT(*) FROM PPQ_EQUIPMENT E WHERE E.PROTOCOL_ID = O.PROTOCOL_ID
                              AND (E.IQ_STATUS <> 'Y' OR E.OQ_STATUS <> 'Y' OR E.PQ_STATUS <> 'Y'));
    IF V_OPEN_APPR > 0 THEN
      SIGNAL SQLSTATE '75001' SET MESSAGE_TEXT = 'Cannot approve: one or more required role approval
    END IF;
    IF V_EQP_INCOMPLETE > 0 THEN
      SIGNAL SQLSTATE '75002' SET MESSAGE_TEXT = 'Cannot approve: one or more linked equipment items
    END IF;
  END IF;
END;

-- Deviation numbering trigger
CREATE OR REPLACE TRIGGER TRG_PPQ_DEVIATION_NO
  BEFORE INSERT ON PPQ_DEVIATION
  REFERENCING NEW ROW AS N
  FOR EACH ROW MODE DB2SQL
BEGIN ATOMIC
  IF N.DEV_NO IS NULL OR N.DEV_NO = '' THEN
    SET N.DEV_NO = 'DEV-' || CHAR(NEXT VALUE FOR SEQ_DEVIATION_NO);
  END IF;
END;
