CREATE VIEW PPQ_YIELD_V AS
SELECT
  PROTOCOL_ID,
  STAGE_SEQ,
  STAGE_NAME,
  THEORETICAL_YIELD,
  ACTUAL_YIELD,
  UOM,
  CASE WHEN THEORETICAL_YIELD IS NULL OR THEORETICAL_YIELD = 0
     OR ACTUAL_YIELD IS NULL THEN NULL
       ELSE ROUND((ACTUAL_YIELD / THEORETICAL_YIELD) * 100, 3)
  END AS PCT_YIELD
FROM PPQ_YIELD;
