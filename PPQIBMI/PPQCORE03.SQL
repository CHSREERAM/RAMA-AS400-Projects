     REFERENCES PPQ_CPP (PROTOCOL_ID, CPP_SEQ),
  CONSTRAINT CK_RSK_RANGE CHECK (SEVERITY BETWEEN 1 AND 10
    AND OCCURRENCE BETWEEN 1 AND 10 AND DETECTION BETWEEN 1 AND 10)
);
LABEL ON TABLE PPQ_RISK IS 'Module 15 - Quality Risk Analysis (FMEA-style)';

--CREATE VIEW PPQ_RISK_V FOR SYSTEM NAME PPQRSKV AS
CREATE VIEW PPQ_RISK_V AS
SELECT
  PROTOCOL_ID,
  RISK_SEQ,
  RISK_DESC,
  CPP_SEQ,
  SEVERITY,
  OCCURRENCE,
  DETECTION,
  -- RPN (Risk Priority Number) = Severity * Occurrence * Detection
  (SEVERITY * OCCURRENCE * DETECTION) AS RPN,
  MITIGATION,
  RESIDUAL_RISK
FROM PPQ_RISK;
LABEL ON TABLE PPQ_RISK_V IS 'Quality Risk Analysis with RPN';


