  RISK_DESC      VARCHAR(150) NOT NULL,
  CPP_SEQ        SMALLINT,
  SEVERITY       SMALLINT    NOT NULL,
  OCCURRENCE     SMALLINT    NOT NULL,
  DETECTION      SMALLINT    NOT NULL,
  --RPN            SMALLINT    GENERATED ALWAYS AS
  --                           (SEVERITY * OCCURRENCE * DETECTION),
