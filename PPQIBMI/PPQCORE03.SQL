-- Module 3: PPQ Protocol Header
------------------------------------------------------------------
CREATE TABLE PPQ_HEADER (
  PROTOCOL_ID     BIGINT        NOT NULL GENERATED ALWAYS AS
                                IDENTITY (START WITH 1 INCREMENT BY 1),
  PROTOCOL_NO     VARCHAR(20)   NOT NULL,             -- formatted business key, e.g. PPQ/2026/00042
  REVISION_NO     SMALLINT      NOT NULL DEFAULT 0,
  VERSION_NO      SMALLINT      NOT NULL DEFAULT 1,
  PRODUCT_CD      CHAR(15)      NOT NULL,
  PRODUCT_NAME    VARCHAR(80)   NOT NULL,
  STRENGTH        VARCHAR(40),
  DOSAGE_FORM     VARCHAR(40),
  MARKET          VARCHAR(60),
  BATCH_SIZE      DECIMAL(15, 3),
  BATCH_SIZE_UOM  CHAR(6),
  VALIDATION_TYPE CHAR(2)       NOT NULL,             -- PR Prospective / CO Concurrent / RV Revalid
  STATUS          VARCHAR(10)   NOT NULL DEFAULT 'DRAFT',
  CREATED_BY      VARCHAR(10)   NOT NULL,
  CREATED_TS      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  UPDATED_BY      VARCHAR(10),
  UPDATED_TS      TIMESTAMP,
  CONSTRAINT PK_PPQ_HEADER PRIMARY KEY (PROTOCOL_ID),
  CONSTRAINT UQ_PPQ_HEADER_NO UNIQUE (PROTOCOL_NO, REVISION_NO),
  CONSTRAINT FK_HDR_PRODUCT FOREIGN KEY (PRODUCT_CD)
     REFERENCES MD_PRODUCT (PRODUCT_CD),
  CONSTRAINT CK_HDR_VTYPE CHECK (VALIDATION_TYPE
      IN ('PR','CO','RV','LG','NP','ST')),
  CONSTRAINT CK_HDR_STATUS CHECK (STATUS IN
      ('DRAFT','REVIEW','APPROVED','EXECUTED','CLOSED'))
);
LABEL ON TABLE PPQ_HEADER IS 'Module 3 - PPQ Protocol Header';
CREATE INDEX IX_HDR_STATUS ON PPQ_HEADER (STATUS, PRODUCT_CD);

